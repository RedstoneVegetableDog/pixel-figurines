#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
原神「赝品立绘」→ 托盘图 + FakeData.g.cs 生成器（像素手办 / 深空当铺正式版）

输入：一个文件夹，里面是 `<角色名>立绘_<部位>.png`（每角色 1~N 张，部位就是这版赝品的缺陷）。
输出：
  1) Tray\\Genshin\\Fake\\figurine_tray_<短id>_fake2.png / _fake3.png / ...
     —— 512×512 RGBA，contain（比照 tools/gen_ip_assets.py 的托盘图规格；`_fake1` 反色图不动）
  2) FakeData.g.cs：原神 120 位的缺陷表
     —— 变体 1 = 反色，变体 2..N = 文件名里的部位（按文件名 Unicode 排序定顺序）

用法：
  python tools/gen_fake_trays.py ^
      --src "E:\\深空当铺正式版mod\\原神赝品立绘" ^
      --catalog "E:\\深空当铺正式版mod\\手办MOD\\src\\FigurineMod\\Catalog.g.cs" ^
      --out "E:\\steam\\steamapps\\common\\Probably Stolen\\Mods\\PixelFigurines\\Tray\\Genshin\\Fake" ^
      --gen-cs "E:\\深空当铺正式版mod\\手办MOD\\src\\FigurineMod\\FakeData.g.cs"

顺序规则：同一角色的多张图按「部位」字符串的 Unicode 码点排序（Python 默认 str 排序），
第 1 张 → 变体 2（_fake2），第 2 张 → 变体 3（_fake3），依此类推。
依赖：Pillow。
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import unicodedata
from pathlib import Path

try:
    from PIL import Image, ImageOps
except ImportError:
    print("缺少 Pillow：先 pip install pillow", file=sys.stderr)
    raise

# Catalog.g.cs 里原神一行的格式：new Def { Id = "figurine_gs_<slug>", Zh = "<名字>", ...
CAT_RE = re.compile(r'Id\s*=\s*"figurine_gs_([^"]+)"\s*,\s*Zh\s*=\s*"([^"]+)"')
FILE_RE = re.compile(r"^(?P<name>.+?)立绘_(?P<part>.+)$")
SUFFIX = "赝品"  # 个别文件名写成「爱诺赝品立绘_螺丝」


def make_square(img: Image.Image, size: int) -> Image.Image:
    """和 gen_ip_assets.py 的托盘图一致：RGBA、contain（透明边不裁）、LANCZOS。"""
    img = img.convert("RGBA")
    w, h = img.size
    side = max(w, h)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(img, ((side - w) // 2, (side - h) // 2), img)
    return canvas.resize((size, size), Image.LANCZOS)


def load_catalog(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8-sig")
    pairs = CAT_RE.findall(text)
    if not pairs:
        raise SystemExit(f"Catalog.g.cs 里没解析到 figurine_gs_ 条目：{path}")
    zh2slug = {}
    for slug, zh in pairs:
        if zh in zh2slug:
            raise SystemExit(f"Catalog 里重名：{zh}")
        zh2slug[zh] = slug
    return zh2slug


def collect(src: Path) -> tuple[dict[str, list[tuple[str, Path]]], list[str]]:
    by_char: dict[str, list[tuple[str, Path]]] = {}
    errors: list[str] = []
    for p in sorted(src.glob("*.png")):
        b = p.stem
        m = FILE_RE.match(b)
        if not m:
            errors.append(f"文件名不符合 <角色>立绘_<部位>：{p.name}")
            continue
        name = m.group("name").replace(SUFFIX, "")
        part = m.group("part").strip()
        if not name or not part:
            errors.append(f"文件名解析为空：{p.name}")
            continue
        by_char.setdefault(name, []).append((part, p))
    # 同一角色内部按 Unicode 排序，保证 _fakeN 顺序稳定
    for name, items in by_char.items():
        items.sort(key=lambda t: t[0])
    return by_char, errors


def write_fakedata(out_cs: Path, zh2slug: dict[str, str], by_char: dict[str, list[str]]) -> None:
    lines: list[str] = []
    lines.append("// <auto-generated> tools/gen_fake_trays.py 生成；请勿手改。")
    lines.append("// 变体 1 = 反色（_fake1 反色托盘图）；变体 2..N = 原神赝品立绘的部位（文件名后缀，按 Unicode 排序）。")
    lines.append("using System.Collections.Generic;")
    lines.append("")
    lines.append("namespace FigurinePort")
    lines.append("{")
    lines.append("    internal static class FakeData")
    lines.append("    {")
    lines.append('        public static readonly Dictionary<string, string[][]> Defects = new Dictionary<string, string[][]>')
    lines.append("        {")
    for zh, slug in zh2slug.items():
        parts = by_char.get(zh, [])
        variants = ['new[] { "反色" }'] + [f'new[] {{ "{p}" }}' for p in parts]
        lines.append(f'            {{ "{slug}", new[] {{ ' + ", ".join(variants) + " } },")
    lines.append("        };")
    lines.append("    }")
    lines.append("}")
    out_cs.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
    print(f"[cs] 已生成 {out_cs}")


def main() -> int:
    ap = argparse.ArgumentParser(description="原神赝品立绘 → Tray Fake 图 + FakeData.g.cs")
    ap.add_argument("--src", required=True, help="赝品立绘文件夹（<角色>立绘_<部位>.png）")
    ap.add_argument("--catalog", required=True, help="Catalog.g.cs（用来把中文名映射成短 id）")
    ap.add_argument("--out", required=True, help="Tray\\Genshin\\Fake 输出目录（不存在会建）")
    ap.add_argument("--gen-cs", required=True, help="FakeData.g.cs 输出路径")
    ap.add_argument("--size", type=int, default=512, help="托盘图边长，默认 512")
    args = ap.parse_args()

    src = Path(args.src)
    if not src.is_dir():
        print(f"赝品立绘目录不存在：{src}", file=sys.stderr)
        return 2
    zh2slug = load_catalog(Path(args.catalog))
    by_char, errors = collect(src)

    unknown = [n for n in by_char if n not in zh2slug]
    if unknown:
        print("在 Catalog 里找不到这些角色：" + "、".join(unknown), file=sys.stderr)
        return 1

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    written = 0
    for zh, items in sorted(by_char.items(), key=lambda kv: zh2slug[kv[0]]):
        slug = zh2slug[zh]
        for i, (part, path) in enumerate(items):
            variant = i + 2  # 变体 1 = 反色，_fake1 不动
            img = Image.open(path)
            make_square(img, args.size).save(out / f"figurine_tray_{slug}_fake{variant}.png", "PNG")
            written += 1
            print(f"[ok] {zh}（{slug}）v{variant} <- {path.name}（{part}）")

    no_art = [zh for zh in zh2slug if zh not in by_char]
    if no_art:
        print("以下角色没有赝品立绘，只保留「反色」变体：" + "、".join(no_art), file=sys.stderr)

    write_fakedata(Path(args.gen_cs), zh2slug, {zh: [p for p, _ in items] for zh, items in by_char.items()})

    print()
    print(f"完成：{written} 张 → {out}")
    if errors:
        print("有错误：", file=sys.stderr)
        for e in errors:
            print("  - " + e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
